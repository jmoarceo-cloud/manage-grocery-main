<?php

if (PHP_SAPI !== 'cli') {
    exit(1);
}
chdir(dirname(__DIR__));
$pipes = [];
$process = proc_open([PHP_BINARY, 'artisan', 'route:list', '--json', '--except-vendor'], [0 => ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes);
fclose($pipes[0]);
$output = stream_get_contents($pipes[1]);
$error = stream_get_contents($pipes[2]);
fclose($pipes[1]);
fclose($pipes[2]);
if (proc_close($process) !== 0) {
    throw new RuntimeException('Route inventory failed.');
}
$routes = json_decode($output, true, 512, JSON_THROW_ON_ERROR);
file_put_contents('docs/audit/LARAVEL_ROUTES.json', json_encode($routes, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)."\n");
$document = file_get_contents('docs/API.md');
$head = explode('## Registered native routes', $document, 2)[0];
$table = "## Registered native routes\n\nGenerated by `php bin/export-routes.php`; excludes vendor and testing-only routes.\n\n| Method | URI | Name | Middleware |\n|---|---|---|---|\n";
foreach ($routes as $route) {
    $cells = [$route['method'], $route['uri'], $route['name'] ?? '', implode(', ', $route['middleware'])];
    $table .= '| '.implode(' | ', array_map(fn ($value) => '`'.str_replace('|', '\\|', $value).'`', $cells))." |\n";
}
file_put_contents('docs/API.md', $head.$table);
echo count($routes)." native routes exported.\n";
